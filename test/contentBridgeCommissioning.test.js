test('F3. a lost response is retried without duplicating', async () => {
  const { a, dd } = syntheticApp();
  const c = a.contentCandidate(dd, 'founder');
  await configured(async () => {
    const m = fakeMonday();
    // The create succeeds on the board but the caller never sees the reply.
    let swallow = true;
    const flaky = async (url, opts) => {
      const r = await m.fetch(url, opts);
      if (swallow && /create_item/.test(JSON.parse(opts.body).query)) {
        swallow = false;
        return { ok: false, status: 502, text: async () => 'gateway' };
      }
      return r;
    };
    const lost = await CB.exportCandidate(c, true, { fetch: flaky });
    assert.equal(lost.ok, false, 'the caller sees a failure');
    assert.equal(m.items.length, 1, 'but the row exists');

    const retry = await CB.exportCandidate(c, true, { fetch: m.fetch });
    assert.equal(retry.ok, true);
    assert.equal(retry.created, false, 'the retry found it rather than repeating it');
    assert.equal(m.items.length, 1, 'still ONE row');
  });
});

