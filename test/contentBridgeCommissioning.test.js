/* A recording monday. Holds items in memory keyed exactly the way the board
 * keys them -- by the Candidate ID column -- so idempotency is exercised against
 * a store that behaves like the real one rather than against a stub that always
 * says "absent". */
function fakeMonday() {
  const items = [];
  const calls = [];
  const fetch = async (url, opts) => {
    const body = JSON.parse(opts.body);
    calls.push({ url, headers: opts.headers, query: body.query, variables: body.variables });
    if (/items_page_by_column_values/.test(body.query)) {
      const want = body.variables.val[0];
      const hit = items.find(i => i.cols[CB.COL.candidateId] === want);
      return reply({ items_page_by_column_values: { items: hit ? [{ id: hit.id, name: hit.name }] : [] } });
    }
    if (/create_item/.test(body.query)) {
      const id = String(9000 + items.length);
      items.push({ id, name: body.variables.name, group: body.variables.group,
                   cols: JSON.parse(body.variables.cols) });
      return reply({ create_item: { id } });
    }
    throw new Error('unexpected query');
  };
  return { fetch, items, calls };
}
const reply = (data) => ({ ok: true, status: 200, text: async () => JSON.stringify({ data }) });

/* The environment a commissioned deployment has. Restored afterwards. */
async function configured(fn, over) {
  const keys = ['MONDAY_API_TOKEN', 'MONDAY_CONTENT_BOARD_ID', 'MONDAY_CONTENT_GROUP_ID',
                'MONDAY_CONTENT_SOURCE_LABEL', 'VVV_CONTENT_BRIDGE_ENABLED'];
  const saved = {};
  keys.forEach(k => { saved[k] = process.env[k]; });
  process.env.MONDAY_API_TOKEN = 'synthetic-not-a-real-token';
  process.env.MONDAY_CONTENT_BOARD_ID = '5102476403';
  process.env.MONDAY_CONTENT_GROUP_ID = GROUP;
  delete process.env.MONDAY_CONTENT_SOURCE_LABEL;
  process.env.VVV_CONTENT_BRIDGE_ENABLED = 'on';
  Object.assign(process.env, over || {});
  try { return await fn(); }
  finally {
    keys.forEach(k => { if (saved[k] === undefined) delete process.env[k]; else process.env[k] = saved[k]; });
  }
}

/* A synthetic block with one deliberately outstanding session. The numbers are
 * the fixture's own targets pushed to the fast edge with heart rate held inside
 * the band -- which is precisely what coachBreakthroughs() already recognises,
 * so eligibility is earned rather than asserted. */
function syntheticApp() {
  const a = loadApp({ pinnedDate: TODAY + 'T09:00:00Z' });
  a.showToast = () => {};
  buildPlan(a, { weeks: 14, startDate: a.addDays(TODAY, -28), distanceKey: 'full',
                 volume: 60, benchSec: 3 * 3600 + 15 * 60 });
  a.state.setup.benchmark = { distanceKey: 'full', timeSec: 3 * 3600 + 15 * 60 };
  a.state.setup.lthr = 172; a.state.setup.maxHR = 197;

  const dd = a.state.days.filter(d => {
    const p = a.prescriptionOf(d);
    return d.date < a.todayStr() && p && p.archetype === 'threshold_continuous';
  })[0];
  assert.ok(dd, 'the synthetic block must contain a quality session');
  const tr = a.executionPaceTarget(dd), z = a.executionHRTarget(dd);
  dd.completed = true;
  dd.actual = { km: dd.km, pace: a.secToPace(tr.fast - 4),
                hr: z && z.lo != null ? z.lo + 2 : 150, rpe: 6, notes: '' };
  return { a, dd };
}

