test('D. forbidden athlete fields cannot leak, by construction and by refusal', async () => {
  const { a, dd } = syntheticApp();
  const c = a.contentCandidate(dd, 'founder');
  const flat = JSON.stringify(c);
  // The distinctive values the athlete logged are absent from the DTO. RPE is
  // checked by key rather than by value: a single digit legitimately appears in
  // a distance and an execution score, so a substring search would be theatre.
  for (const secret of [dd.actual.pace, String(dd.actual.hr)]) {
    assert.equal(flat.indexOf(secret), -1, 'logged value leaked: ' + secret);
  }
  for (const k of ['rpe', 'hr', 'pace', 'notes', 'feel'])
    assert.equal(k in c, false, 'prohibited key present: ' + k);
  for (const k of CB.PROHIBITED) assert.equal(k in c, false, 'prohibited key present: ' + k);

  // And the server refuses one that is tampered with in flight.
  await configured(async () => {
    const m = fakeMonday();
    const out = await CB.exportCandidate(Object.assign({}, c, { hr: 151 }), true, { fetch: m.fetch });
    assert.equal(out.ok, false);
    assert.equal(out.status, 400);
    assert.ok(out.problems.includes('prohibited_field_present'));
    assert.equal(m.calls.length, 0, 'a rejected candidate never reaches monday');
  });
});

