-- ===========================================================================
-- COACH MEMORY: ONE LINE AT A TIME, KEPT ONLY IF THE ATHLETE ASKED FOR IT
--
-- Founder, approving Phase 4: the coach should not ask the same thing twice
-- and should be able to pick up where the athlete left off. So it keeps a
-- short note of what the two of them talked about and the choices the athlete
-- made ("Declined the extra run, week 5"), and reads the most recent few back
-- as BACKGROUND the next time the athlete asks it something.
--
-- WHAT A ROW IS. One athlete, one date, one kind, one line of at most 200
-- characters. Nothing else. No session data, no paces, no heart rate, no run
-- notes, no model output, and nothing from Strava -- the server builds every
-- line itself, either from a fixed sentence (a decision or a flag) or from
-- the athlete's own question, trimmed and checked (a conversation). See
-- api/_coach-memory-lines.js for exactly what may become a line.
--
-- WHO CAN DO WHAT
--   the athlete      READ their own lines. Nothing else -- no insert, no
--                    update, no delete from a browser. Clearing goes through
--                    the server (POST /api/coach-memory {action:'clear'}),
--                    which deletes by the uid a verified token names.
--   the server       writes, with the service key, only lines it has built
--                    and checked itself, and only for a verified athlete who
--                    has turned Coach Memory on.
--   anyone else      nothing. The anonymous key sees no row.
--
-- WHY CLEARING IS NOT A CLIENT DELETE POLICY. A delete policy would be
-- harmless on its own, but every write path a browser holds is one more thing
-- to prove, and the server already has the one it needs: the same verified
-- uid that wrote the lines removes them, and the same function is what
-- account deletion and an erasure request call. With no client write policy
-- of any kind, every row in this table is provably a row the server checked.
--
-- HOW IT GOES AWAY
--   Clear memory     every line, at once, from Settings.
--   account deleted  ON DELETE CASCADE from auth.users, and the server also
--                    deletes them explicitly so it does not depend on that.
--   health erasure   every line marked `health` (pain, illness and the like)
--                    is deleted; the rest of the record stays.
--   over time        only the newest 100 lines per athlete are kept (STEP 3).
--
-- WHERE IT SITS IN THE ORDER. After supabase-security-posture.sql (file 10),
-- like files 11 and 12: the table is created with row-level security on in
-- the statement after it exists, so re-running 10 afterwards passes. It needs
-- nothing from files 2 to 12.
--
-- Safe to re-run.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- STEP 1 -- THE TABLE
--
-- The checks are the second line of the server's own rules, so a bug in the
-- server cannot store something the rules forbid:
--   * one line, 1 to 200 characters, no line breaks
--   * never the word Strava, in any case -- "Nothing from Strava is ever kept"
--     is in the consent wording, so it is in the schema too
--   * one of three kinds
-- `health` marks a line about the athlete's body. The server only ever writes
-- one with health-data consent in force, and an erasure request deletes them.
-- The unique constraint is what "it won't ask you the same thing twice" costs
-- in storage: the same line on the same day is kept once.
-- ---------------------------------------------------------------------------
create table if not exists public.coach_memory (
  id          bigint      generated by default as identity primary key,
  user_id     uuid        not null references auth.users(id) on delete cascade,
  day         date        not null,
  kind        text        not null check (kind in ('decision','conversation','flag')),
  line        text        not null,
  health      boolean     not null default false,
  created_at  timestamptz not null default now(),
  constraint coach_memory_line_length check (char_length(btrim(line)) between 1 and 200
                                             and char_length(line) <= 200),
  constraint coach_memory_one_line    check (line !~ '[\r\n]'),
  constraint coach_memory_no_strava   check (line !~* 'strava'),
  constraint coach_memory_once        unique (user_id, day, line)
);
alter table public.coach_memory enable row level security;

-- The two queries the product makes: this athlete's newest lines, and the
-- prune in STEP 3.
create index if not exists coach_memory_user_created_idx
  on public.coach_memory (user_id, created_at desc);


-- ---------------------------------------------------------------------------
-- STEP 2 -- ROW-LEVEL SECURITY, AND THE GRANTS UNDER IT
--
-- ONE POLICY: read your own lines, signed in. There is no INSERT, UPDATE or
-- DELETE policy, so with RLS on every browser write is refused. The table
-- privileges are taken away as well, so the refusal does not rest on RLS
-- alone: if a policy were ever added by hand, the GRANT layer would still say
-- no until somebody also put the privilege back on purpose.
--
-- (select auth.uid()) rather than a bare auth.uid(), for the InitPlan reason
-- written out in supabase-security-posture.sql.
-- ---------------------------------------------------------------------------
drop policy if exists "own coach memory: select" on public.coach_memory;
create policy "own coach memory: select" on public.coach_memory
  for select to authenticated using ((select auth.uid()) = user_id);

revoke all on table public.coach_memory from anon;
revoke insert, update, delete, truncate on table public.coach_memory from authenticated;


-- ---------------------------------------------------------------------------
-- STEP 3 -- KEEP THE NEWEST 100 LINES, AND NO MORE
--
-- Six to eight lines ever reach the coach. A hundred is enough for the athlete
-- to read back what has been kept, and is a bound rather than a promise to
-- keep everything forever. Done in the database so it holds whichever server
-- path wrote the row.
-- ---------------------------------------------------------------------------
create or replace function public.coach_memory_keep_recent()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  delete from public.coach_memory
   where user_id = new.user_id
     and id in (select m.id from public.coach_memory m
                 where m.user_id = new.user_id
                 order by m.created_at desc, m.id desc
                 offset 100);
  return null;
end $$;

drop trigger if exists coach_memory_keep_recent on public.coach_memory;
create trigger coach_memory_keep_recent
  after insert on public.coach_memory
  for each row execute function public.coach_memory_keep_recent();

-- A trigger function is never called directly by anyone.
revoke all on function public.coach_memory_keep_recent() from public, anon, authenticated;


-- ---------------------------------------------------------------------------
-- STEP 4 -- REFUSE IF THE POSTURE IS WRONG
--
-- Everything above is idempotent, so on a second run this file's value is in
-- what it CHECKS. Each is a way the notes could leak or be forged without
-- anybody noticing. It raises rather than repairs: a posture that drifted did
-- so for a reason, and silently rewriting it would hide the reason.
-- ---------------------------------------------------------------------------
do $$
declare
  v text; n integer;
begin
  -- 1. Row-level security on.
  if not (select c.relrowsecurity from pg_class c where c.oid = 'public.coach_memory'::regclass) then
    raise exception using errcode = 'raise_exception',
      message = 'coach_memory has row-level security OFF. Nothing has been changed.';
  end if;

  -- 2. No client write policy of any kind.
  select string_agg(policyname || ' (' || cmd || ')', ', ') into v
    from pg_policies
   where schemaname = 'public' and tablename = 'coach_memory' and cmd <> 'SELECT';
  if v is not null then
    raise exception using errcode = 'raise_exception',
      message = 'coach_memory is written only by the server, but these policies let a browser write it: '
             || v || '. Nothing has been changed.';
  end if;

  -- 3. Every policy for signed-in users only, and scoped to the caller.
  select string_agg(policyname, ', ') into v
    from pg_policies
   where schemaname = 'public' and tablename = 'coach_memory'
     and (roles <> '{authenticated}'
          or coalesce(qual, '') || coalesce(with_check, '') not like '%auth.uid()%');
  if v is not null then
    raise exception using errcode = 'raise_exception',
      message = 'These coach_memory policies reach beyond the athlete''s own lines: '
             || v || '. Nothing has been changed.';
  end if;

  -- 4. The GRANT layer agrees: no browser role may write, the anonymous key
  --    may not even read.
  if has_table_privilege('authenticated', 'public.coach_memory', 'insert')
     or has_table_privilege('authenticated', 'public.coach_memory', 'update')
     or has_table_privilege('authenticated', 'public.coach_memory', 'delete')
     or has_table_privilege('anon', 'public.coach_memory', 'select') then
    raise exception using errcode = 'raise_exception',
      message = 'coach_memory table privileges let a browser role write it, or the anonymous key read it. '
             || 'Nothing has been changed.';
  end if;

  -- 5. The line checks are present. Without them a server bug stores anything.
  select count(*) into n from pg_constraint
   where conrelid = 'public.coach_memory'::regclass
     and conname in ('coach_memory_line_length', 'coach_memory_one_line',
                     'coach_memory_no_strava', 'coach_memory_once');
  if n <> 4 then
    raise exception using errcode = 'raise_exception',
      message = 'coach_memory is missing ' || (4 - n) || ' of its line checks. Nothing has been changed.';
  end if;
  if not exists (select 1 from pg_constraint
                  where conrelid = 'public.coach_memory'::regclass and contype = 'c'
                    and pg_get_constraintdef(oid) like '%''decision''%''conversation''%''flag''%') then
    raise exception using errcode = 'raise_exception',
      message = 'coach_memory.kind is not limited to decision, conversation and flag. Nothing has been changed.';
  end if;

  -- 6. The prune runs on the empty search path and nobody can call it.
  select string_agg(p.proname, ', ') into v
    from pg_proc p join pg_namespace ns on ns.oid = p.pronamespace
   where ns.nspname = 'public' and p.proname like 'coach_memory%'
     and (p.proconfig is null or not ('search_path=""' = any(p.proconfig))
          or has_function_privilege('anon', p.oid, 'execute')
          or has_function_privilege('authenticated', p.oid, 'execute'));
  if v is not null then
    raise exception using errcode = 'raise_exception',
      message = 'These coach_memory functions are callable or not pinned to the empty search path: '
             || v || '. Nothing has been changed.';
  end if;

  raise notice 'Coach memory: row-level security, grants and line checks are as designed.';
end $$;

